#!/usr/bin/env python3
"""Builds infaq.js: «الإنفاق في سبيل الله» ayat (spending in Allah's cause, zakat, charity).
Text from api.alquran.cloud: quran-uthmani (Arabic) + en.pickthall (English, Pickthall). Do not hand-edit."""
import json, urllib.request
REFS = ["2:261","2:274","9:60","57:7","64:16","3:92","2:267","2:245","2:43","2:177","9:103","63:10","34:39","73:20"]
out = []
for ref in REFS:
    u = f"https://api.alquran.cloud/v1/ayah/{ref}/editions/quran-uthmani,en.pickthall"
    d = json.load(urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "all-apps"}), timeout=30))["data"]
    out.append({"ref": ref, "surah": d[0]["surah"]["name"], "surahEn": d[0]["surah"]["englishName"],
                "ar": d[0]["text"], "en": d[1]["text"]})
open("infaq.js", "w").write("/* الإنفاق في سبيل الله — api.alquran.cloud quran-uthmani + en.pickthall. Generated by gen_infaq.py */\nvar INFAQ=" + json.dumps(out, ensure_ascii=False) + ";\n")
print(len(out), "ayat")
